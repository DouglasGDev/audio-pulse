const dictionaries: Record<Language, Record<MessageKey, string>> = {
  "pt-BR": pt,
  en,
};

export function translate(
  language: Language,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let text = dictionaries[language][key] ?? pt[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}

export function presetTitle(language: Language, preset: Preset): string {
  const key = `preset.${preset.id}.name`;
  if (key in pt) {
    return translate(language, key as MessageKey);
  }
  return preset.name;
}

export function presetDescription(language: Language, preset: Preset): string {
  const key = `preset.${preset.id}.desc`;
  if (key in pt) {
    return translate(language, key as MessageKey);
  }
  if (preset.category === "headphone") {
    if (language === "en") {
      return translate("en", "preset.headphoneDesc", {
        brand: preset.brand ?? "",
        model: preset.model ?? "",
      }).trim();
    }
    return preset.description;
  }
  if (preset.category === "custom") {
    return translate(language, "preset.customDesc");
  }
  return preset.description;
}

export function categoryLabel(language: Language, category: Preset["category"]): string {
  return translate(language, `category.${category}` as MessageKey);
}

export function detectedLanguage(value: string): Language {
  if (value === "pt-BR" || value === "en") {
    return value;
  }
  const browser = typeof navigator !== "undefined" ? navigator.language : "en";
  return browser.toLowerCase().startsWith("pt") ? "pt-BR" : "en";
}